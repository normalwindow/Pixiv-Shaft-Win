        fun forLocale(locale: String): L10n {
            val resolved = when (locale) {
                "zh", "en", "ja" -> locale
                "" -> java.util.Locale.getDefault().language.let { if (it in setOf("en", "ja")) it else "zh" }
                else -> "zh"
            }
            return when (resolved) {
                "en" -> L10n("en", EN)
                "ja" -> L10n("ja", JA)
                else -> L10n("zh", ZH)
            }
        }
    }
}

